// Waits for a Wii Remote to connect (the player can give up with the buttons of the system pad).
int muNameTask::mainStepRemoteSimpleSyncMain(muNameTask* task) {
    bool done = false;
    if (task->m_timer > 0) {
        if (--task->m_timer == 0) {
            fn_8002B504(g_gfPadSystem);
        }
        return task->m_step;
    }
    int channel = 0;
    do {
        int type;
        if (fn_8021A024(channel, &type) == 0) {
            break;
        }
        channel++;
    } while (channel < 4);
    if (channel >= 4) {
        gfPadStatus pad;
        g_gfPadSystem->getSysPadStatus(GF_PAD_SYSTEM_GET_ALL_PADS, &pad);
        if ((pad.m_buttonsPressedThisFrame.bits & GF_PAD_BUTTON_BIT_START) != 0 || (pad.m_buttonsPressedThisFrame.bits & GF_PAD_BUTTON_BIT_B) != 0) {
            playSE(2);
            done = true;
        }
    } else {
        task->m_remotePadNo = channel;
        done = true;
        task->m_remote->m_pad = channel;
    }
    if (done) {
        return Step_RemoteSimpleSyncStop;
    }
    return task->m_step;
}

