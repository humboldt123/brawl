// The list of the names: A picks the name (the line of the new name opens the keyboard), B leaves, the directions move the cursor.
int muNameTask::mainStepSelectNameMain(muNameTask* task) {
    int count = task->m_slotCount;
    bool moved = false;
    bool scrolled = false;
    gfPadStatus pad;
    g_gfPadSystem->getSysPadStatus(task->m_padNo, &pad);
    u32 ctrlBits = ctrlWord(task, 0x10);
    u32 pressed = pad.m_buttonsPressedThisFrame.bits;
    if ((pressed & GF_PAD_BUTTON_BIT_B) != 0) {
        task->m_resultKind = Result_Cancelled;
        task->m_resultNameNo = 0;
        return Step_Leave;
    }
    if (task->m_remote != NULL && (pressed & (0x00800000 | GF_PAD_BUTTON_BIT_START)) != 0) {
        if (fn_8004D148(g_GameGlobal) <= 0) {
            task->m_remoteNameNo = -1;
        } else {
            const muNameSlot* slot = &task->m_slots[task->m_scroll + task->m_cursor];
            const muNameSlot* use = slot;
            if (slot->m_nameNo == -1) {
                use = slot + 1;
            } else if (slot->m_nameNo == -2) {
                use = slot - 1;
            }
            task->m_remoteNameNo = use->m_nameNo;
        }
        return Step_RemoteSimpleSync;
    }
    u32 decide = task->m_remote == NULL ? GF_PAD_BUTTON_BIT_A | GF_PAD_BUTTON_BIT_START : GF_PAD_BUTTON_BIT_A;
    if ((pressed & decide) != 0) {
        const muNameSlot* slot = &task->m_slots[task->m_scroll + task->m_cursor];
        if (slot->m_taken) {
            playSE(3);
        } else {
            task->m_playerNo = fn_800BA2E0();
            int id = slot->m_nameNo;
            int nameNo = -1;
            if (id != -2 && id != -1) {
                nameNo = id;
            }
            if (nameNo == -1) {
                if (fn_8004D740(g_GameGlobal) <= 0) {
                    playSE(3);
                    return Step_NameFull;
                }
                playSE(1);
                return Step_NameEntry;
            }
            playSE(1);
            task->m_resultNameNo = nameNo;
            task->m_resultKind = Result_Chosen;
        }
    }
    if ((ctrlBits & GF_PAD_BUTTON_BIT_DPAD_UP) != 0) {
        if (task->m_cursor != 0) {
            task->m_cursor--;
            moved = true;
        } else if (task->m_scroll != 0) {
            task->m_scroll--;
            scrolled = true;
        }
    }
    if ((ctrlBits & GF_PAD_BUTTON_BIT_DPAD_DOWN) != 0) {
        if (task->m_scroll + task->m_cursor < count - 1) {
            if (task->m_cursor < 4) {
                task->m_cursor++;
                moved = true;
            } else if (task->m_scroll < count - 5) {
                task->m_scroll++;
                scrolled = true;
            }
        }
    }
    if (moved || scrolled) {
        task->updateAll();
        playSE(0);
    }
    return task->m_step;
}

