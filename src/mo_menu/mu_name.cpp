// Orders the names of the list: the new name line comes first, the names follow in the order of the record of the game.
static int compareNameSlots(const void* a, const void* b) {
    s16 nameA = static_cast<const muNameSlot*>(a)->m_nameNo;
    s16 nameB = static_cast<const muNameSlot*>(b)->m_nameNo;
    if (nameA == -1) {
        return -1;
    }
    if (nameB == -1) {
        return 1;
    }
    if (nameA == -2) {
        return 1;
    }
    if (nameB == -2) {
        return -1;
    }
    char* dataA = static_cast<char*>(fn_8004D138(g_GameGlobal, nameA));
    char* dataB = static_cast<char*>(fn_8004D138(g_GameGlobal, nameB));
    int diff = *reinterpret_cast<int*>(dataB + 0xF0) - *reinterpret_cast<int*>(dataA + 0xF0);
    if (diff == 0) {
        return nameA - nameB;
    }
    return diff;
}

