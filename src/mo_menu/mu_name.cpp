// Moves the cursor on the keys with the directions: the keys are in rows of three (1 to 12), the top key (0) deletes and the
// done key (13) decides.
void MuSelctChrNameEntry::cursorMain(gfPadStatus* pad) {
    int cursor = m_cursor;
    if ((pad->m_buttonsPressedThisFrame.bits & GF_PAD_BUTTON_BIT_START) != 0) {
        m_savedCursor = Cursor_Next;
        cursor = Cursor_Done;
    }
    if ((pad->m_buttonsPressedThisFrame2.bits & GF_PAD_BUTTON_BIT_DPAD_UP) != 0) {
        if (cursor == Cursor_Done) {
            cursor = m_savedCursor;
        } else {
            cursor -= 3;
            if (cursor < 0) {
                cursor = 0;
            }
        }
        if (cursor == 0 && m_cursor != 0) {
            m_savedCursor = m_cursor;
        }
    }
    if ((pad->m_buttonsPressedThisFrame2.bits & GF_PAD_BUTTON_BIT_DPAD_DOWN) != 0) {
        if (cursor == 0) {
            cursor = m_savedCursor;
        } else {
            cursor += 3;
            if (cursor >= 14) {
                cursor = Cursor_Done;
            }
        }
        if (cursor == Cursor_Done && m_cursor != Cursor_Done) {
            m_savedCursor = m_cursor;
        }
    }
    u32 buttons = pad->m_buttonsPressedThisFrame2.bits;
    if ((buttons & GF_PAD_BUTTON_BIT_DPAD_RIGHT) != 0 && cursor != 0 && cursor != Cursor_Done && cursor % 3 != 0) {
        cursor++;
    }
    if ((buttons & GF_PAD_BUTTON_BIT_DPAD_LEFT) != 0 && cursor != 0 && cursor != Cursor_Done && cursor % 3 != 1) {
        cursor--;
    }
    if (cursor != m_cursor) {
        float frame = static_cast<float>(cursor + 1);
        m_base->setFrameMatCol(frame);
        if (m_curSetObj != NULL) {
            m_curSetObj->setFrameMatCol(frame);
        }
        m_cursorObj->setFrameNode(frame);
        m_cursor = cursor;
        m_caretAtEnd = true;
        updateCaret();
        playSE(0);
    }
}

