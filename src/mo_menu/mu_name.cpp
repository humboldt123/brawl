// Starts to read what the Wii Remote keeps.
void muNameRemoteTask::read() {
    m_readRetries = 0;
    m_wait = 0;
    g_gfPadSystem->readGameDataRequest(m_pad & 0xFF, reinterpret_cast<int>(m_readBuf), sGameDataSize, 0);
    m_result = 1;
    m_state = State_Reading;
}

// How the request for the data ended: the data has to belong to the game (the owner name of the Wii Remote and a sum of the bytes
// are checked).
int muNameRemoteTask::getReadStatus() {
    if (!isGameDataRequestOver()) {
        return Status_Busy;
    }
    int code = getGameDataRequestCode();
    if (code != 0) {
        if (code == -6) {
            return Status_Unknown4;
        }
        if (code == -5) {
            return Status_Unknown3;
        }
        return Status_NoRemote;
    }
    const u16* ownerName;
    if (fn_802253B4(m_pad, &ownerName) != 0) {
        return Status_BadData;
    }
    wchar_t magic[0x20];
    Message::utf8to16(magic, sRemoteMagic);
    const u16* a = ownerName;
    const u16* b = reinterpret_cast<const u16*>(magic);
    bool same = true;
    while (*a != 0 || *b != 0) {
        if (*a != *b) {
            same = false;
            break;
        }
        a++;
        b++;
    }
    if (!same) {
        return Status_BadData;
    }
    bool empty = true;
    for (int i = 0; i < 0x3C; i++) {
        if (m_readBuf[i] != 0) {
            empty = false;
            break;
        }
    }
    if (empty) {
        return Status_BadData;
    }
    u32 sum = 0;
    for (int i = 0; i < 0x3C; i++) {
        sum += m_readBuf[i];
    }
    if (*reinterpret_cast<u32*>(&m_readBuf[0x3C]) != sum) {
        return Status_BadData;
    }
    return Status_Ok;
}

void muNameRemoteTask::readProcess() {
    if (m_wait > 0) {
        if (--m_wait <= 0) {
            g_gfPadSystem->readGameDataRequest(m_pad & 0xFF, reinterpret_cast<int>(m_readBuf), sGameDataSize, 0);
        }
        return;
    }
    int status = getReadStatus();
    if (status == Status_Busy) {
        return;
    }
    if (status == Status_Ok) {
        m_result = 0;
        m_state = State_Idle;
        return;
    }
    if (m_readRetries >= 3) {
        m_result = status;
        m_state = State_Idle;
        return;
    }
    m_readRetries++;
    m_wait = 5;
}

// Starts to write the name to the Wii Remote (the sum of the bytes is added to the data).
void muNameRemoteTask::write(const muNameRemoteData* data) {
    memcpy(m_writeBuf, data, 0x3C);
    m_writeRetries = 0;
    m_verifying = false;
    u32 sum = 0;
    for (int i = 0; i < 0x3C; i++) {
        sum += m_writeBuf[i];
    }
    *reinterpret_cast<u32*>(&m_writeBuf[0x3C]) = sum;
    g_gfPadSystem->writeGameDataRequest(m_pad & 0xFF, reinterpret_cast<int>(m_writeBuf), sGameDataSize, 0);
    m_result = 1;
    m_state = State_Writing;
    m_verifying = false;
}

// Waits for the write, then reads the data back and compares it; a write that failed is tried again up to 3 times.
void muNameRemoteTask::writeProcess() {
    if (m_verifying) {
        int status = getReadStatus();
        if (status == Status_Busy) {
            return;
        }
        if (status == Status_Ok && memcmp(m_readBuf, m_writeBuf, sGameDataSize) == 0) {
            m_result = 0;
            m_state = State_Idle;
            return;
        }
        if (m_writeRetries >= 3) {
            m_result = Status_Failed;
            m_state = State_Idle;
            return;
        }
        g_gfPadSystem->writeGameDataRequest(m_pad & 0xFF, reinterpret_cast<int>(m_writeBuf), sGameDataSize, 0);
        m_verifying = false;
        m_wait = 0;
        m_writeRetries++;
        return;
    }
    if (m_wait > 0) {
        if (--m_wait <= 0) {
            g_gfPadSystem->writeGameDataRequest(m_pad & 0xFF, reinterpret_cast<int>(m_writeBuf), sGameDataSize, 0);
        }
        return;
    }
    int status;
    if (!g_gfPadSystem->m_flags35.f7) {
        status = Status_Busy;
    } else {
        status = Status_Ok;
        if (getGameDataRequestCode() != 0) {
            status = Status_Failed;
        }
    }
    if (status == Status_Busy) {
        return;
    }
    if (status == Status_Ok) {
        m_readRetries = 0;
        m_wait = 0;
        g_gfPadSystem->readGameDataRequest(m_pad & 0xFF, reinterpret_cast<int>(m_readBuf), sGameDataSize, 0);
        m_result = 1;
        m_verifying = true;
        return;
    }
    if (m_writeRetries >= 3) {
        m_result = status;
        m_state = State_Idle;
        return;
    }
    m_writeRetries++;
    m_wait = 5;
}
