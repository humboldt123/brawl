// Whether the name can be used: the names of the computer players, of the guests and of the players cannot.
bool MuSelctChrNameEntry::isNameValid(const char* name) {
    char* cpuName;
    char* guestPrefix;
    char* cpuPrefix;
    char** playerNames;
    if (getLanguage__10GameGlobalFv(g_GameGlobal) == 0) {
        cpuName = sJpCpuName;
        playerNames = sJpPlayerNames;
        guestPrefix = sJpGuestPrefix;
        cpuPrefix = sJpCpuPrefix;
    } else {
        cpuName = sEnCpuName;
        playerNames = sEnPlayerNames;
        guestPrefix = sEnNoPrefix;
        cpuPrefix = sEnCpuPrefix;
    }
    if (strcmp(cpuName, name) == 0) {
        return false;
    }
    if (!isNameValidNumeric(name, guestPrefix, 2, 1, 0x20)) {
        return false;
    }
    if (!isNameValidNumeric(name, cpuPrefix, 2, 1, 0x20)) {
        return false;
    }
    while (*playerNames != NULL) {
        if (strcmp(*playerNames, name) == 0) {
            return false;
        }
        playerNames++;
    }
    return true;
}

// Whether the name is not the prefix followed by a number (as full-width digits) between min and max.
bool MuSelctChrNameEntry::isNameValidNumeric(const char* name, const char* prefix, int digits, int min, int max) {
    int prefixLen = msgLen(prefix);
    if (prefixLen + digits == msgLen(name) && strncmp(prefix, name, strlen(prefix)) == 0) {
        int number = 0;
        int i = 0;
        while (i < digits) {
            char letter[4];
            letter[0] = 0;
            appendSubstr__7MessageFPcPCcii(letter, name, prefixLen + i, 1);
            wchar_t wide[2];
            Message::utf8to16(wide, letter);
            if (wide[0] < 0xFF10 || wide[0] > 0xFF19) {
                break;
            }
            number = number * 10 + (wide[0] - 0xFF10);
            i++;
        }
        if (i >= digits && number >= min && number <= max) {
            return false;
        }
    }
    return true;
}

